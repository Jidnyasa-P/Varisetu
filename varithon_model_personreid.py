"""## 19. Verification (Same/Different Person) — ROC-AUC

Reframing Re-ID as **pairwise verification** is the one place ROC-AUC is actually meaningful here: given two
person-crop embeddings, is this the *same* physical person (positive) or *different* people (negative)?
This mirrors what the control-room officer confirmation step does in practice, and it's the metric that
maps most directly onto "how often would the system produce a confusing false-positive suggestion."

Pairs are sampled from Query+Gallery embeddings (never from train) so this, like CMC/mAP, is an open-set
measurement.
"""

def sample_verification_pairs(embed, pids, camids, num_pos=5000, num_neg=5000, seed=SEED):
    rng = np.random.RandomState(seed)
    n = len(pids)
    pid_to_idx = defaultdict(list)
    for i, pid in enumerate(pids):
        if pid in (0, -1):
            continue
        pid_to_idx[pid].append(i)
    valid_pids = [p for p, idxs in pid_to_idx.items() if len(idxs) >= 2]

    pos_scores, neg_scores = [], []

    # Positive pairs: same identity, different image (ideally different camera)
    while len(pos_scores) < num_pos:
        pid = rng.choice(valid_pids)
        i, j = rng.choice(pid_to_idx[pid], size=2, replace=False)
        pos_scores.append(float(embed[i] @ embed[j]))

    # Negative pairs: different identities
    all_valid_idx = [i for i, p in enumerate(pids) if p not in (0, -1)]
    while len(neg_scores) < num_neg:
        i, j = rng.choice(all_valid_idx, size=2, replace=False)
        if pids[i] != pids[j]:
            neg_scores.append(float(embed[i] @ embed[j]))

    scores = np.array(pos_scores + neg_scores)
    labels = np.array([1] * len(pos_scores) + [0] * len(neg_scores))   # 1 = same person
    return scores, labels


