def load_reid_inference(export_dir, device=None):
    """Everything a backend needs to call, independent of this notebook."""
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    with open(os.path.join(export_dir, "model_config.json")) as f:
        cfg = json.load(f)

    m = ReIDModel(num_classes=cfg["num_train_classes"], embedding_dim=cfg["embedding_dim"]).to(device)
    m.load_state_dict(torch.load(os.path.join(export_dir, "reid_model.pt"), map_location=device))
    m.eval()

    tfm = T.Compose([
        T.Resize((cfg["img_size"]["height"], cfg["img_size"]["width"])),
        T.ToTensor(),
        T.Normalize(cfg["normalize_mean"], cfg["normalize_std"]),
    ])

    @torch.no_grad()
    def embed_image(pil_image):
        x = tfm(pil_image.convert("RGB")).unsqueeze(0).to(device)
        pooled, _, _ = m(x)
        return F.normalize(pooled, dim=1).cpu().numpy()[0]

    return embed_image, cfg


