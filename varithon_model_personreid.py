def run_epoch_train(model, loader, optimizer):
    model.train()
    total_loss, total_ce, total_tri = 0.0, 0.0, 0.0
    all_preds, all_labels = [], []

    for imgs, labels, pids, camids in loader:
        imgs, labels = imgs.to(DEVICE), labels.to(DEVICE)

        optimizer.zero_grad()
        pooled, bn_feat, logits = model(imgs)

        ce = ce_loss_fn(logits, labels)
        tri = triplet_loss_fn(pooled, labels)
        loss = ce + TRIPLET_WEIGHT * tri

        loss.backward()
        optimizer.step()

        total_loss += loss.item() * imgs.size(0)
        total_ce += ce.item() * imgs.size(0)
        total_tri += tri.item() * imgs.size(0)
        all_preds.append(logits.argmax(dim=1).detach().cpu().numpy())
        all_labels.append(labels.detach().cpu().numpy())

    n = len(loader.dataset) if hasattr(loader, "dataset") else len(all_labels) * loader.batch_size
    n = sum(len(l) for l in all_labels)
    y_true = np.concatenate(all_labels); y_pred = np.concatenate(all_preds)
    acc = accuracy_score(y_true, y_pred)
    prec, rec, f1, _ = precision_recall_fscore_support(y_true, y_pred, average="macro", zero_division=0)
    return {"loss": total_loss / n, "ce_loss": total_ce / n, "triplet_loss": total_tri / n,
            "accuracy": acc, "precision_macro": prec, "recall_macro": rec, "f1_macro": f1}


