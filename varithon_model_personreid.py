class PKSampler(Sampler):
    """Batch-hard triplet loss needs P identities x K images-per-identity per batch, not a
    plain random shuffle, or there may be zero valid triplets in a batch."""
    def __init__(self, df, num_ids_per_batch=16, num_imgs_per_id=4):
        self.df = df
        self.P = num_ids_per_batch
        self.K = num_imgs_per_id
        self.id_to_indices = defaultdict(list)
        for idx, pid in enumerate(df.person_id.values):
            self.id_to_indices[pid].append(idx)
        self.pids = [pid for pid, idxs in self.id_to_indices.items() if len(idxs) >= 1]
        self.length = (len(self.pids) // self.P) * self.P * self.K

    def __iter__(self):
        pids = self.pids.copy()
        random.shuffle(pids)
        batches = []
        for i in range(0, len(pids) - self.P + 1, self.P):
            batch_pids = pids[i:i + self.P]
            batch = []
            for pid in batch_pids:
                idxs = self.id_to_indices[pid]
                if len(idxs) >= self.K:
                    chosen = random.sample(idxs, self.K)
                else:
                    chosen = random.choices(idxs, k=self.K)   # sample with replacement if too few
                batch.extend(chosen)
            batches.append(batch)
        random.shuffle(batches)
        flat = [i for b in batches for i in b]
        return iter(flat)

    def __len__(self):
        return self.length


