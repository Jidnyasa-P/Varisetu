def evaluate_cmc_map(q_embed, q_pids, q_camids, g_embed, g_pids, g_camids, ranks=(1, 5, 10)):
    """Standard Market-1501 CMC/mAP protocol: for each query, rank all gallery images by
    cosine distance, but SKIP gallery entries that are junk (pid==0), distractor (pid==-1),
    or the exact same identity captured by the exact same camera (that would be a trivial
    'match' of the same physical photo series, not a genuine cross-camera re-identification)."""
    sim = q_embed @ g_embed.T
    dist = 1 - sim
    num_q = dist.shape[0]

    all_cmc, all_ap = [], []
    for i in range(num_q):
        order = np.argsort(dist[i])
        g_pids_sorted = g_pids[order]
        g_camids_sorted = g_camids[order]

        valid = ~(((g_pids_sorted == q_pids[i]) & (g_camids_sorted == q_camids[i])) |
                  (g_pids_sorted == 0) | (g_pids_sorted == -1))
        g_pids_valid = g_pids_sorted[valid]

        matches = (g_pids_valid == q_pids[i]).astype(np.int32)
        if matches.sum() == 0:
            continue   # no valid ground truth for this query, skip (standard protocol)

        cmc = matches.cumsum()
        cmc[cmc > 1] = 1
        all_cmc.append(cmc[:max(ranks)])

        num_rel = matches.sum()
        tmp_cmc = matches.cumsum()
        precision_at_k = tmp_cmc / (np.arange(len(matches)) + 1)
        ap = (precision_at_k * matches).sum() / num_rel
        all_ap.append(ap)

    all_cmc = np.array(all_cmc)
    cmc_curve = all_cmc.mean(axis=0)
    result = {f"Rank-{r}": cmc_curve[r - 1] for r in ranks}
    result["mAP"] = float(np.mean(all_ap))
    result["_cmc_curve"] = cmc_curve
    return result


