"""## 14. Model & Losses

**Backbone:** ResNet-50, ImageNet-pretrained (transfer learning — training a CNN from scratch on ~11K train
images would badly overfit; ImageNet features transfer well to person imagery).

**BNNeck:** a BatchNorm1d layer (no bias) between the pooled feature and the classifier. This is the single
highest-value trick from the "Bag of Tricks" Re-ID baseline: the **pre-BN feature** is used for the triplet
loss (keeps it well-clustered by cosine similarity) and the **post-BN feature** is used for classification —
using one shared feature for both losses measurably hurts Re-ID performance because the two losses pull the
same feature space in different directions.

**Loss = Cross-Entropy (label smoothing 0.1) + Batch-Hard Triplet Loss (margin 0.3).**
- CE trains the identity-classification head (gives us accuracy/precision/recall/F1 during training).
- Triplet loss directly optimizes what the deployed system needs: same-identity embeddings pulled together,
  different-identity embeddings pushed apart, using the hardest positive/negative in each PK-batch.
"""

class ReIDModel(nn.Module):
    def __init__(self, num_classes, embedding_dim=2048):
        super().__init__()
        backbone = resnet50(weights=ResNet50_Weights.IMAGENET1K_V2)
        # Standard Re-ID trick: drop the stride in the last residual stage so the final
        # feature map has more spatial resolution (helps with small/occluded person crops).
        backbone.layer4[0].downsample[0].stride = (1, 1)
        backbone.layer4[0].conv2.stride = (1, 1)
        self.backbone = nn.Sequential(*list(backbone.children())[:-2])  # drop avgpool+fc
        self.gap = nn.AdaptiveAvgPool2d(1)
        self.bnneck = nn.BatchNorm1d(embedding_dim)
        self.bnneck.bias.requires_grad_(False)   # no-bias BNNeck, per Bag-of-Tricks
        self.classifier = nn.Linear(embedding_dim, num_classes, bias=False)

    def forward(self, x):
        feat_map = self.backbone(x)
        pooled = self.gap(feat_map).flatten(1)         # pre-BN embedding (for triplet loss / inference)
        bn_feat = self.bnneck(pooled)                   # post-BN embedding (for classification)
        logits = self.classifier(bn_feat)
        return pooled, bn_feat, logits


class BatchHardTripletLoss(nn.Module):
    def __init__(self, margin=0.3):
        super().__init__()
        self.margin = margin

    def forward(self, embeddings, labels):
        # pairwise Euclidean distance matrix
        dist = torch.cdist(embeddings, embeddings, p=2)
        labels = labels.unsqueeze(1)
        same = labels.eq(labels.t())
        diff = ~same

        # hardest positive: max distance among same-identity pairs (excluding self)
        dist_pos = dist.clone()
        dist_pos[~same] = -1
        dist_pos.fill_diagonal_(-1)
        hardest_pos = dist_pos.max(dim=1).values

        # hardest negative: min distance among different-identity pairs
        dist_neg = dist.clone()
        dist_neg[same] = float("inf")
        hardest_neg = dist_neg.min(dim=1).values

        loss = F.relu(hardest_pos - hardest_neg + self.margin)
        return loss.mean()


